#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
VENV_DIR="$ROOT/.venv"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

JUDGE_MODEL="${LLM_MEM_JUDGE_MODEL:-gpt-4o-mini}"
JUDGE_URL="${LLM_MEM_JUDGE_BASE_URL:-https://api.openai.com/v1}"
JUDGE_KEY="${LLM_MEM_JUDGE_API_KEY:-${OPENAI_API_KEY:-}}"

echo "=== llm-mem Benchmark Setup ==="
echo ""

# 1. Build llm-mem with Vulkan
echo "[1/6] Building llm-mem-mcp with Vulkan..."
cd "$ROOT"
cargo build --release --features "default,vulkan" --bin llm-mem-mcp
echo "  Done: target/release/llm-mem-mcp"

# 2. Install Python deps via uv into project .venv
echo "[2/6] Installing Python dependencies..."
if [ ! -d "$VENV_DIR" ]; then
    uv venv "$VENV_DIR"
fi
"$VENV_DIR/bin/pip" install mcp openai tqdm rouge-score 2>/dev/null || \
    uv pip install --python "$VENV_DIR/bin/python" mcp openai tqdm rouge-score
echo "  Done"

# 3. Download LongMemEval datasets
echo "[3/6] Downloading LongMemEval datasets..."
LONGMEMEVAL_DIR="$ROOT/benchmark-data/longmemeval"
mkdir -p "$LONGMEMEVAL_DIR"

BASE_URL="https://huggingface.co/datasets/xiaowu0162/longmemeval-cleaned/resolve/main"
for f in longmemeval_s_cleaned.json longmemeval_m_cleaned.json longmemeval_oracle.json; do
    if [ ! -f "$LONGMEMEVAL_DIR/$f" ]; then
        echo "  Downloading $f..."
        wget -q --show-progress -O "$LONGMEMEVAL_DIR/$f" "$BASE_URL/$f" || {
            echo "  WARNING: Failed to download $f (may need HF token)"
        }
    else
        echo "  $f already exists, skipping"
    fi
done

# 4. Clone LoCoMo dataset and LongMemEval eval scripts
echo "[4/6] Cloning benchmark dependencies..."
LOCOMO_DEPS="$ROOT/benchmark-deps/locomo"
if [ ! -d "$LOCOMO_DEPS" ]; then
    git clone --depth 1 https://github.com/snap-research/locomo.git "$LOCOMO_DEPS" || {
        echo "  WARNING: Failed to clone LoCoMo repo"
    }
fi

LOCOMO_DATA="$ROOT/benchmark-data/locomo"
mkdir -p "$LOCOMO_DATA"
if [ -f "$LOCOMO_DEPS/data/locomo10.json" ] && [ ! -f "$LOCOMO_DATA/locomo10.json" ]; then
    ln -sf "$LOCOMO_DEPS/data/locomo10.json" "$LOCOMO_DATA/locomo10.json"
    echo "  Done: symlinked locomo10.json"
fi

LME_EVAL="$ROOT/benchmark-deps/longmemeval"
if [ ! -d "$LME_EVAL" ]; then
    echo "  Cloning LongMemEval eval repo..."
    git clone --depth 1 https://github.com/xiaowu0162/LongMemEval.git "$LME_EVAL"
    if [ -f "$LME_EVAL/requirements-lite.txt" ]; then
        "$VENV_DIR/bin/pip" install -r "$LME_EVAL/requirements-lite.txt" 2>/dev/null || true
    fi
fi


# 5. Validate judge LLM
echo "[5/6] Validating judge LLM..."
if [ -z "$JUDGE_KEY" ]; then
    echo -e "  ${YELLOW}SKIP${NC}  No API key set (LLM_MEM_JUDGE_API_KEY or OPENAI_API_KEY)."
    echo "  Set your key and re-run to validate:"
    echo "    export LLM_MEM_JUDGE_API_KEY=your-key"
    echo "    export LLM_MEM_JUDGE_MODEL=your-model    # default: gpt-4o-mini"
    echo "    export LLM_MEM_JUDGE_BASE_URL=http://...  # default: OpenAI"
else
    echo "  Model   : $JUDGE_MODEL"
    echo "  Endpoint: $JUDGE_URL"
    echo ""
    if "$VENV_DIR/bin/python" "$ROOT/benchmark/validate_judge.py" \
        --model "$JUDGE_MODEL" \
        --base-url "$JUDGE_URL" \
        --api-key "$JUDGE_KEY"; then
        echo ""
        echo -e "  ${GREEN}Judge LLM is ready.${NC}"
    else
        echo ""
        echo -e "  ${RED}Judge LLM validation FAILED. Fix issues before running benchmarks.${NC}"
        exit 1
    fi
fi

# 6. Generate API benchmark configs
#
# The `benchmark/config_*_api.toml` files point at a private LLM endpoint and
# are therefore kept out of version control — this step generates them from
# env vars if they don't already exist.
echo "[6/6] Generating API benchmark configs..."
GEN_URL="${LLM_MEM_LLM_BASE_URL:-http://localhost:8080/v1}"
GEN_KEY="${LLM_MEM_LLM_API_KEY:-${OPENAI_API_KEY:-local}}"
GEN_MODEL="${LLM_MEM_ANSWER_MODEL:-gemma-4-E4B-it-GGUF}"

gen_api_config() {  # gen_api_config <variant> <max_tokens> <concurrency> <batch_max_tokens> <enable_abstraction> <chunk_size>
    local variant="$1" max_tokens="$2" conc="$3" batch_max="$4" abstraction="$5" chunk_size="$6"
    local dst="$ROOT/benchmark/config_${variant}_api.toml"
    if [ -f "$dst" ]; then
        echo "  $(basename "$dst") already exists, skipping"
        return 0
    fi
    cat > "$dst" <<EOF
# llm-mem benchmark — ${variant^^} variant (remote LLM + local embedding)
# Generated by scripts/setup_benchmarks.sh from env vars; not committed.
# Embeddings stay local (fastembed) for simplicity and speed.
[llm]
provider = "api"
api_url = "$GEN_URL"
model = "$GEN_MODEL"
api_key = "$GEN_KEY"
context_size = 131072
temperature = 0.1
max_tokens = $max_tokens
request_format = "auto"
use_structured_output = false
structured_output_retries = 3
max_concurrent_requests = $conc
batch_size = 10
batch_max_tokens = $batch_max
batch_timeout_secs = 120
batch_timeout_multiplier = 1.0
llm_timeout_secs = 600

# Local model settings (not used when provider = "api")
model_file = "$GEN_MODEL"
models_dir = "llm-mem-data/models"
gpu_layers = 99
cpu_threads = 0
auto_download = true
cache_model = true
use_grammar = false

[embedding]
provider = "local"
model = "all-MiniLM-L6-v2"

[vector_store]
store_type = "lancedb"
collection_name = "llm-memories"
banks_dir = "llm-mem-data/banks"

[vector_store.lancedb]
table_name = "memories"
database_path = "./lancedb"
embedding_dimension = 384

[memory]
max_memories = 100000
similarity_threshold = 0.65
max_search_results = 50
auto_summary_threshold = 32768
enable_abstraction = $abstraction
skip_duplicates = true
merge_threshold = 0.75
search_similarity_threshold = 0.25
max_content_length = 65536
document_chunk_size = $chunk_size

[server]
host = "0.0.0.0"
port = 8000

[logging]
enabled = true
log_directory = "benchmark/logs/server"
level = "info"
max_size_mb = 10
max_files = 3
EOF
    echo "  Generated: $(basename "$dst") (endpoint: $GEN_URL)"
}

gen_api_config "flat" 4096 7 3000 false 4000
gen_api_config "pyramid" 1024 12 1000 true 1024

echo ""
echo "=== Setup Complete ==="
echo ""
echo "Run LongMemEval-S (fast, ~30 min):"
echo "  bash scripts/run_benchmark.sh"
echo ""
echo "Run with custom judge (if not using env vars):"
echo "  bash scripts/run_benchmark.sh --judge-model \"$JUDGE_MODEL\" --judge-url \"$JUDGE_URL\" --judge-key \"$JUDGE_KEY\""
